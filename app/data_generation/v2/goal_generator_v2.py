def _active_career_goal(career_goals: str) -> str | None:
    """career_goals에서 능동적 목표 문장 추출 (현상 유지 제외)."""
    active_kw = ["원합니다", "싶어", "하고자", "되고", "성장", "목표", "키우", "이루", "만들", "추진"]
    passive_kw = ["만족", "유지", "현상", "지금처럼", "무리하지"]
    for sentence in career_goals.replace("。", ".").split("."):
        s = sentence.strip()
        if len(s) < 15:
            continue
        if any(pw in s for pw in passive_kw):
            continue
        if any(aw in s for aw in active_kw):
            return s.rstrip(".") + "."
    return None


