# ── 쿼터 기반 도메인 선택 ───────────────────────────────────────────────────────
def _assign_goal_noise(
    counter: dict[float, int],
    targets: dict[float, int],
    rng: random.Random,
) -> float:
    """쿼터 기반 noise_ratio 배정 — deficit 가장 큰 level 중 랜덤 선택."""
    levels = list(targets.keys())
    deficits = {n: counter.get(n, 0) - targets[n] for n in levels}
    min_def = min(deficits.values())
    candidates = [n for n in levels if deficits[n] <= min_def + 1]
    chosen = rng.choice(candidates)
    counter[chosen] = counter.get(chosen, 0) + 1
    return chosen


def _select_domains_with_quota(
    preferred: list[str],
    n: int,
    counter: dict[str, int],
    targets: dict[str, int],
    rng: random.Random,
) -> list[str]:
    """1순위 = 페르소나 선호 도메인(쿼터 남은 것), 2순위 = 전체 중 deficit 큰 도메인."""
    def deficit(d: str) -> float:
        return counter.get(d, 0) - targets.get(d, 13)

    under_preferred = [d for d in preferred if deficit(d) < 0]
    rng.shuffle(under_preferred)
    chosen = under_preferred[:n]

    if len(chosen) < n:
        fill_pool = [d for d in targets if d not in chosen]
        fill_pool.sort(key=deficit)
        for d in fill_pool:
            if len(chosen) >= n:
                break
            chosen.append(d)

    rng.shuffle(chosen)
    return chosen


def generate_goals_v2(
    user_id: str,
    persona: PersonaProfile,
    min_goals: int = 3,
    max_goals: int = 5,
    seed: int = 42,
    domain_counter: dict[str, int] | None = None,
    domain_targets: dict[str, int] | None = None,
    noise_counter: dict[float, int] | None = None,
    noise_targets: dict[float, int] | None = None,
) -> list[ResearchGoal]:
    """페르소나 기반 goal 생성 (30-domain, 쿼터 균형, 페르소나 description)."""
    rng = random.Random(seed)
    num_goals = rng.randint(min_goals, max_goals)

    if domain_counter is not None and domain_targets is not None:
        chosen_domains = _select_domains_with_quota(
            persona.inferred_domains, num_goals, domain_counter, domain_targets, rng
        )
        for d in chosen_domains:
            domain_counter[d] = domain_counter.get(d, 0) + 1
    else:
        domains = persona.inferred_domains[:] or ["health", "growth"]
        rng.shuffle(domains)
        chosen_domains = domains[:num_goals]
        fallback = ["health", "growth", "social", "entertainment", "order"]
        for fb in fallback:
            if len(chosen_domains) < min_goals and fb not in chosen_domains:
                chosen_domains.append(fb)

    goals: list[ResearchGoal] = []
    used: set[str] = set()

    for j, domain in enumerate(chosen_domains[:max_goals]):
        pool = _GOAL_POOL.get(domain, _GOAL_POOL["growth"])
        candidates = [p for p in pool if p[0] not in used]
        if not candidates:
            candidates = pool
        long_term, mid_term, short_term = rng.choice(candidates)
        used.add(long_term)

        noise = 0.0
        if noise_counter is not None and noise_targets is not None:
            noise = _assign_goal_noise(noise_counter, noise_targets, rng)

        goals.append(ResearchGoal(
            goal_id=f"G-{user_id}-{j+1:02d}",
            user_id=user_id,
            domain=domain,
            long_term=long_term,
            mid_term=mid_term,
            short_term=short_term,
            status="active",
            noise_ratio=noise,
            created_at="2026-01-01",
        ))

    return goals
